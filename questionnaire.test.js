const schema = require('./questionnaire.js');
const explanation = require('./assessment-explanation.js');

function fixture(gender = 'Nam', brushing = 3) {
  const administration = { name: 'Test', gender };
  const answers = schema.questions.map(q => q.multiple ? [q.none] : 0);
  answers[10] = brushing;
  schema.questions.forEach((q, i) => { if (schema.skipped(i, answers, administration)) answers[i] = null; });
  return { questionnaireVersion: 2, administration, answers, answerDetails: {}, photoKind: 'test', warningSigns: [], warningScreened: true };
}
const male = fixture();
assert(schema.complete(male.answers, male.administration));
assert.equal(male.answers[8], null);
assert.deepEqual(male.answers.slice(11, 14), [null, null, null]);
